CREATE TABLE IF NOT EXISTS analysis_task (
 id VARCHAR(36) PRIMARY KEY,
 workspace VARCHAR(64) NOT NULL,
 idem VARCHAR(128) NOT NULL,
 request_json CLOB NOT NULL,
 dataset_base64 CLOB NOT NULL,
 source_sha VARCHAR(64) NOT NULL,
 created_at BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','CANCELLED')),
 attempt INTEGER NOT NULL DEFAULT 0,
 lease_token VARCHAR(36),
 lease_until BIGINT NOT NULL DEFAULT 0,
 available_at BIGINT NOT NULL DEFAULT 0,
 result_json CLOB,
 result_hash VARCHAR(64),
 error_code VARCHAR(80),
 CONSTRAINT task_idempotency UNIQUE(workspace, idem)
);
CREATE INDEX IF NOT EXISTS task_ready ON analysis_task(status, available_at, lease_until);
ALTER TABLE analysis_task ADD COLUMN IF NOT EXISTS category VARCHAR(16) NOT NULL DEFAULT 'analysis';
ALTER TABLE analysis_task ADD COLUMN IF NOT EXISTS expires_at BIGINT NOT NULL DEFAULT 0;
UPDATE analysis_task SET expires_at=created_at+900000 WHERE expires_at=0;
CREATE INDEX IF NOT EXISTS task_expiry ON analysis_task(status,expires_at);
CREATE TABLE IF NOT EXISTS task_event (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id VARCHAR(36) NOT NULL REFERENCES analysis_task(id),
 event_at BIGINT NOT NULL,
 kind VARCHAR(32) NOT NULL,
 attempt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS dataset_import_guard (workspace VARCHAR(64) PRIMARY KEY);
MERGE INTO dataset_import_guard(workspace) KEY(workspace) VALUES ('demo-shop');
ALTER TABLE dataset_import_guard ADD COLUMN IF NOT EXISTS worker_last_poll_at BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS dataset_import (
 id VARCHAR(36) PRIMARY KEY,
 workspace VARCHAR(64) NOT NULL,
 idem VARCHAR(128) NOT NULL,
 upload_hash VARCHAR(64) NOT NULL,
 name VARCHAR(120) NOT NULL,
 files_json CLOB NOT NULL,
 mapping_json CLOB NOT NULL DEFAULT 'null',
 created_at BIGINT NOT NULL,
 revision INTEGER NOT NULL DEFAULT 0,
 check_task_id VARCHAR(36),
 version_id VARCHAR(80),
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT import_idempotency UNIQUE(workspace,idem)
);
CREATE TABLE IF NOT EXISTS dataset_check (
 task_id VARCHAR(36) PRIMARY KEY REFERENCES analysis_task(id),
 draft_id VARCHAR(36) NOT NULL REFERENCES dataset_import(id),
 revision INTEGER NOT NULL,
 report_json CLOB NOT NULL,
 mapping_json CLOB NOT NULL,
 snapshot_base64 CLOB,
 snapshot_sha VARCHAR(64),
 review_sha VARCHAR(64) NOT NULL
);
CREATE TABLE IF NOT EXISTS dataset_version (
 id VARCHAR(80) PRIMARY KEY,
 workspace VARCHAR(64) NOT NULL,
 draft_id VARCHAR(36) NOT NULL REFERENCES dataset_import(id),
 check_task_id VARCHAR(36) NOT NULL REFERENCES dataset_check(task_id),
 metadata_json CLOB NOT NULL,
 snapshot_base64 CLOB NOT NULL,
 snapshot_sha VARCHAR(64) NOT NULL,
 model_allowed BOOLEAN NOT NULL,
 created_at BIGINT NOT NULL
);
